BASE_PATH = Path('vocabulary/n_grams/bigrams')

for chunk, translations in TRANSLATIONS.items():
    path = BASE_PATH / f'chunk_{chunk:03}.tsv'
    rows = []
    updated = False
    pending = list(translations)
    with path.open(newline='') as f:
        reader = csv.DictReader(f, delimiter='\t')
        fieldnames = reader.fieldnames
        for row in reader:
            if not row['translation_en'].strip():
                if not pending:
                    raise ValueError(f'Not enough translations for chunk {chunk}')
                row['translation_en'] = pending.pop(0)
                updated = True
            rows.append(row)
    if pending:
        if updated:
            raise ValueError(f'Too many translations for chunk {chunk}')
        print(f'Skipping chunk {chunk}; no blank translations found')
        continue
    if updated:
        with path.open('w', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames, delimiter='\t', lineterminator='\n')
            writer.writeheader()
            writer.writerows(rows)
    else:
        print(f'No updates applied to {path}')
