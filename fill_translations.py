for path, translations in targets.items():
    p = Path(path)
    rows = list(csv.reader(p.open(), delimiter='\t'))
    if len(translations) != len(rows) - 1:
        raise SystemExit(f"Translation count mismatch for {path}: {len(translations)} vs {len(rows)-1}")
    rows[0][-1] = 'translation_en'
    for row, translation in zip(rows[1:], translations):
        if len(row) < 10:
            row.extend([''] * (10 - len(row)))
        row[9] = translation
    with p.open('w', newline='') as f:
        writer = csv.writer(f, delimiter='\t', lineterminator='\n')
        writer.writerows(rows)
